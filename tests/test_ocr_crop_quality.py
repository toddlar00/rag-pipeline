import pytest

import ocr_crop_quality as quality
from ocr_crop_raster_view import build_raster_view


def encoded(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, allow_nan=False,
                      separators=(",", ":")).encode("utf-8")


def retag(value, key):
    value[key] = hashlib.sha256(encoded({k: v for k, v in value.items() if k != key})).hexdigest()
    return value


def fixture(width=4, height=4, *, gray=None, rgb=None, profile="dpi288", clip=None,
            pixels=None, native_clip=None, display=None, rotation=0):
    scale = {"fit": 2.0, "dpi288": 4.0, "dpi576": 8.0}[profile]
    clip = list(clip or [0.0, 0.0, width / scale, height / scale])
    display = list(display or [0.0, 0.0, 512.0, 512.0])
    dw, dh = display[2] - display[0], display[3] - display[1]
    cropbox = [16.0, 32.0, 16.0 + (dh if rotation in (90, 270) else dw),
               32.0 + (dw if rotation in (90, 270) else dh)]
    scope = retag({"source_sha256": "a" * 64, "page_count": 2, "page_number": 2,
        "coordinate_system": "original_page_display_fraction",
        "bbox": [(clip[i] - display[i % 2]) / (dw if i % 2 == 0 else dh) for i in range(4)],
        "page_geometry": {"display_rect_points": display, "cropbox_points": cropbox,
                          "rotation_degrees": rotation}}, "scope_sha256")
    if rgb is None:
        rgb = bytes(channel for level in (gray if gray is not None else [128] * (width * height))
                    for channel in (level, level, level))
    matrix = [scale, 0.0, 0.0, scale, 0.0, 0.0]
    native = list(clip if native_clip is None else native_clip)
    view = build_raster_view(scope=scope, preview_profile=profile, command_clip=clip,
        command_matrix=matrix, native_clip=native, native_matrix=matrix,
        projected_rect=[value * scale for value in native], pixel_rect=list(pixels or [0, 0, width, height]),
        width=width, height=height, rgb_sha256=hashlib.sha256(rgb).hexdigest())
    return rgb, scope, view


def observe(case):
    rgb, scope, view = case
    return quality.inspect_crop_pixels(rgb, scope=scope, raster_view=view)


def edge_map(result):
    return {edge["edge"]: edge for edge in result["edges"]}


def test_exact_rgb_grayscale_coefficients_and_adjacent_pairs_without_wrap():
    result = observe(fixture(4, 1, rgb=bytes([255, 0, 0, 0, 255, 0, 0, 0, 255, 255, 255, 255])))
    values = result["measurements"]
    assert {i: n for i, n in enumerate(values["histogram"]) if n} == {29: 1, 77: 1, 149: 1, 255: 1}
    assert (values["min"], values["max"], values["p05"], values["p95"]) == (29, 255, 29, 255)
    assert values["horizontal_gradient"] == {"sum": 418, "count": 3}
    assert values["vertical_gradient"] == {"sum": 0, "count": 0}
    assert result["status"] == "ambiguous"
    assert "adjacent_pairs_unavailable_on_an_axis" in result["reasons"]


def test_exact_histogram_gradient_and_global_quarter_range_edge_counts():
    result = observe(fixture(4, 2, gray=[0, 10, 20, 30, 40, 50, 60, 255]))
    values = result["measurements"]
    assert values["sample_count"] == 8 and sum(values["histogram"]) == 8
    assert values["horizontal_gradient"] == {"sum": 245, "count": 6}
    assert values["vertical_gradient"] == {"sum": 345, "count": 4}
    assert (values["min"], values["max"], values["p05"], values["p95"]) == (0, 255, 0, 255)
    edges = edge_map(result)
    assert [(edges[name]["low_extreme_count"], edges[name]["high_extreme_count"])
            for name in ("left", "top", "right", "bottom")] == [(4, 0), (7, 1), (3, 1), (7, 1)]
    assert result["work"]["edge_sample_visits"] == 24  # Corners count independently.
    assert result["work"]["sample_visits"] == 32


def test_percentiles_use_exact_nearest_rank_not_interpolation():
    values = observe(fixture(5, 4, gray=list(range(20))))["measurements"]
    assert (values["p05"], values["p95"]) == (0, 18)
    assert values["histogram"] == [1] * 20 + [0] * 236


