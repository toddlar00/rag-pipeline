"""Pure constructed RGB/geometry controls; no images, PDFs, native code or OCR.

Fixtures pass the real raster-view builder/validator. Numeric expectations are
hand-calculated, not generated by the measurement implementation under test.
These observations do not establish real scan quality or representative gain.
"""

import ast
