def test_valid_tiny_scope_with_no_centers_retains_empty_edge_unavailability():
    result = observe(fixture(1, 1, clip=[.015625, .015625, .03125, .03125]))
    assert result["requested_pixel_bbox"] == [.0625, .0625, .125, .125]
    for edge in result["edges"]:
        assert edge["status"] == "unavailable"
        assert edge["ideal_sample_count"] == edge["available_sample_count"] == 0
        assert edge["available_pixel_box"] == [0, 0, 0, 0]
        assert edge["min"] is None and edge["low_extreme_count"] is None
        assert edge["geometric_missing_coverage"] is False
    assert "empty_edge_samples" in result["reasons"]


def test_half_open_fractional_edges_exclude_neighbor_row_column_and_include_low_ties():
    # Requested [.5,.5,4.5,4.5]; centers .5 are included, 4.5 excluded.
    # Dark outer row/column are present in the admitted raster but not any band.
    gray = [255 if x < 4 and y < 4 else 0 for y in range(5) for x in range(5)]
    result = observe(fixture(5, 5, gray=gray, clip=[.125, .125, 1.125, 1.125]))
    assert result["requested_pixel_bbox"] == [.5, .5, 4.5, 4.5]
    expected = {"left": [0, 0, 2, 4], "top": [0, 0, 4, 2],
                "right": [2, 0, 4, 4], "bottom": [0, 2, 4, 4]}
    for edge in result["edges"]:
        assert edge["available_pixel_box"] == expected[edge["edge"]]
        assert edge["ideal_sample_count"] == edge["available_sample_count"] == 8
        assert edge["low_extreme_count"] == 0 and edge["high_extreme_count"] == 8
        assert edge["geometric_missing_coverage"] is False
        assert edge["status"] == "ambiguous"  # Uniform band, not clear.
    assert result["measurements"]["histogram"][0] == 9


def test_tolerance_contraction_geometry_missing_even_without_missing_centers():
    # Same explicit dyadic tolerance example retained in the pure raster suite;
    # constructed declaration only, not a new native-render observation.
    delta = .000244140625
    result = observe(fixture(32, 32, profile="fit", clip=[delta, delta, 16 + delta, 16 + delta]))
    assert result["requested_pixel_bbox"] == [.00048828125, .00048828125, 32.00048828125, 32.00048828125]
    for edge in result["edges"]:
        assert edge["ideal_sample_count"] == edge["available_sample_count"] == 64
        assert edge["missing_sample_count"] == 0
        assert edge["geometric_missing_coverage"] is True and edge["status"] == "partial"
    assert "partial_edge_geometry" in result["reasons"]


def test_native_rounding_partial_centers_have_exact_ideal_and_available_denominators():
    # Explicit binary32 nearest rounding of -8388608.375 to -8388608.0.
    clip = [-8388608.375, -8388608.375, -8388592.0, -8388592.0]
    result = observe(fixture(32, 32, profile="fit", clip=clip,
        native_clip=[-8388608.0, -8388608.0, -8388592.0, -8388592.0],
        pixels=[-16777216, -16777216, -16777184, -16777184],
        display=[-8388609.0, -8388609.0, -8388545.0, -8388545.0]))
    assert result["requested_pixel_bbox"] == [-.75, -.75, 32.0, 32.0]
    edges = edge_map(result)
    assert [(edges[name]["ideal_sample_count"], edges[name]["available_sample_count"],
             edges[name]["missing_sample_count"]) for name in ("left", "top", "right", "bottom")] == [
                 (66, 32, 34), (66, 32, 34), (66, 64, 2), (66, 64, 2)]
    assert all(edge["status"] == "partial" for edge in result["edges"])


