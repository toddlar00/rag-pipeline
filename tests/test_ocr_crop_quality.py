@pytest.mark.parametrize("change", ["short", "long", "same_length_wrong_rgb", "wrong_rgb_hash"])
def test_length_and_hash_fail_before_grayscale_allocation_or_pixel_measurement(monkeypatch, change):
    rgb, scope, view = fixture()
    if change == "short":
        rgb = rgb[:-1]
    elif change == "long":
        rgb += b"\0"
    elif change == "same_length_wrong_rgb":
        rgb = bytes([129]) + rgb[1:]
    else:
        view["rgb_sha256"] = "b" * 64
        retag(view, "view_sha256")
    monkeypatch.setattr(quality, "_measure", lambda *_: pytest.fail("measurement before byte binding"))
    monkeypatch.setattr(quality, "bytearray", lambda *_: pytest.fail("gray allocated"), raising=False)
    with pytest.raises(ValueError, match="advisory input"):
        quality.inspect_crop_pixels(rgb, scope=scope, raster_view=view)


@pytest.mark.parametrize("target", ["scope", "view"])
@pytest.mark.parametrize("change", ["extra", "missing", "wrong_type"])
def test_top_level_cardinality_and_type_refuse_before_hashing_or_membership(monkeypatch, target, change):
    rgb, scope, view = fixture()
    selected = scope if target == "scope" else view
    if change == "extra":
        selected["extra"] = object()
    elif change == "missing":
        selected.pop("source_sha256")
    else:
        selected = []
        if target == "scope":
            scope = selected
        else:
            view = selected
    monkeypatch.setattr(quality.hashlib, "sha256", lambda *_: pytest.fail("hashed malformed cardinality"))
    with pytest.raises(ValueError, match="advisory input"):
        quality.inspect_crop_pixels(rgb, scope=scope, raster_view=view)


