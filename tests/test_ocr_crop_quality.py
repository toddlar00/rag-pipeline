def test_invalid_nested_types_geometry_and_hashes_are_static_before_measurement(monkeypatch, target, path, value):
    rgb, scope, view = fixture()
    destination = scope if target == "scope" else view
    for part in path[:-1]:
        destination = destination[part]
    destination[path[-1]] = value
    monkeypatch.setattr(quality, "_measure", lambda *_: pytest.fail("measured invalid metadata"))
    with pytest.raises(ValueError, match="^invalid crop pixel advisory input or binding$"):
        quality.inspect_crop_pixels(rgb, scope=scope, raster_view=view)


@pytest.mark.parametrize("failure", [KeyboardInterrupt(), SystemExit(3), MemoryError("bounded allocation failed")])
def test_measurement_cancellation_and_allocation_failure_keep_identity(monkeypatch, failure):
    case = fixture()
    def fail(*_):
        raise failure
    monkeypatch.setattr(quality, "_measure", fail)
    with pytest.raises(type(failure)) as observed:
        observe(case)
    assert observed.value is failure


def test_worst_admitted_raster_uses_one_auxiliary_byte_per_pixel_and_bounded_passes(monkeypatch):
    count = 1400 * 1400
    case = fixture(1400, 1400, rgb=b"\x80" * (3 * count))
    allocations = []
    def allocate(size):
        allocations.append(size)
        return builtins.bytearray(size)
    monkeypatch.setattr(quality, "bytearray", allocate, raising=False)
    result = observe(case)
    assert allocations == [count]
    assert result["work"]["auxiliary_gray_bytes"] == count == quality.MAX_PREVIEW_PIXELS
    assert result["work"]["edge_sample_visits"] == 11200
    assert result["work"]["sample_visits"] == count + 11200 <= quality.MAX_SAMPLE_VISITS
    assert result["work"]["adjacent_pair_visits"] == 3917200 <= quality.MAX_ADJACENT_PAIR_VISITS
    assert result["measurements"]["horizontal_gradient"] == {"sum": 0, "count": 1958600}
    assert result["measurements"]["vertical_gradient"] == {"sum": 0, "count": 1958600}
    assert len(encoded(result)) <= 16 * 1024


def test_result_schema_hash_and_all_nested_mutability_are_detached():
    case = fixture(gray=list(range(16)))
    original_rgb, scope, view = case
    before = encoded([scope, view])
    result = observe(case)
    assert set(result) == {"schema_version", "kind", "recipe", "binding", "requested_pixel_bbox",
        "status", "reasons", "measurements", "edges", "advice_codes", "work", "observation_sha256"}
    assert result["binding"] == {key: view[key] for key in ("source_sha256", "scope_sha256", "view_sha256",
        "rgb_sha256", "preview_profile", "width", "height")} | {"page_number": 2}
    expected_hash = hashlib.sha256(b"rag-pipeline:ocr-crop-quality-observation:v1\0" + encoded(
        {key: value for key, value in result.items() if key != "observation_sha256"})).hexdigest()
    assert result["observation_sha256"] == expected_hash
    assert result == json.loads(encoded(result)) and result == observe(case)
    saved = deepcopy(result)
    result["recipe"]["histogram_bins"] = 0
    result["binding"]["source_sha256"] = "f" * 64
    result["measurements"]["histogram"][0] = 100
    result["edges"][0]["available_pixel_box"][0] = 100
    result["requested_pixel_bbox"][0] = 100.0
    assert encoded([scope, view]) == before and case[0] is original_rgb
    assert observe(case) == saved


def test_module_has_only_declared_inward_and_stdlib_imports_without_native_ui_routes():
    source = Path(inspect.getfile(quality)).read_text(encoding="utf-8")
    tree = ast.parse(source)
    modules = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            modules.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            modules.add(node.module)
    assert modules == {"__future__", "hashlib", "json", "math", "ocr_crop_comparison", "ocr_crop_raster_view"}
    assert not any(isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                   and node.func.id in {"eval", "exec", "__import__", "open"} for node in ast.walk(tree))
