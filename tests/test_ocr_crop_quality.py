@pytest.mark.parametrize("name,gray", [
    ("sparse", [255] * 99 + [0]),
    ("reversed", [0] * 99 + [255]),
    ("faint", [127, 128] * 50),
    ("rule", [0] * 10 + [255] * 90),
    ("checker_nontext", [0, 255] * 50),
])
def test_appearance_controls_never_become_text_blur_safe_or_confidence_classifications(name, gray):
    result = observe(fixture(10, 10, gray=gray))
    assert result["recipe"]["annotation_policy"] == "annots_on_rendered_appearance_only"
    assert result["recipe"]["acquisition_resolution"] == "unknown"
    assert "measurements_are_not_text_or_accuracy" in result["advice_codes"]
    assert not ({"safe", "clear", "text", "blur", "quality_score", "confidence"} & set(result))
    if name in ("sparse", "reversed"):
        assert result["status"] == "ambiguous" and "percentile_range_collapsed" in result["reasons"]


def test_reversal_swaps_polarity_hypotheses_without_changing_gradients():
    gray = [0, 10, 20, 30, 40, 50, 60, 255]
    first, second = (observe(fixture(4, 2, gray=values)) for values in (gray, [255 - n for n in gray]))
    assert first["measurements"]["horizontal_gradient"] == second["measurements"]["horizontal_gradient"]
    for before, after in zip(first["edges"], second["edges"]):
        assert before["low_extreme_count"] == after["high_extreme_count"]
        assert before["high_extreme_count"] == after["low_extreme_count"]


def test_profiles_bind_distinct_render_specific_measurements_not_acquisition_ppi():
    results = []
    for profile, scale in (("fit", 2), ("dpi288", 4), ("dpi576", 8)):
        results.append(observe(fixture(scale * 2, scale, profile=profile)))
    assert [result["binding"]["preview_profile"] for result in results] == ["fit", "dpi288", "dpi576"]
    assert len({result["binding"]["scope_sha256"] for result in results}) == 1
    assert len({result["observation_sha256"] for result in results}) == 3
    assert all(result["recipe"]["acquisition_resolution"] == "unknown" for result in results)


