        export = next(block for block in ui.app.fns.values() if block.fn is not None
                      and any(getattr(component, "label", None) == label for component in block.inputs))
        queued = await _capture_queued(ui, export, [True, None, initial["column_context"]], session_hash=session_hash)
        if kind == "assignment":
            await _process(ui, _block(ui, "start_assignments"), [None], session, session_hash)
        inputs = [None, False, initial["column_context"]] if kind == "layout" else [None]
