def _candidate():
    bounds = [(80, 50, 800, 100)]
    for y in (300, 400, 500):
        bounds.extend([(100, y, 350, y + 50), (600, y, 850, y + 50)])
    bounds.append((80, 900, 700, 940))
    lines = [{"text": f"Synthetic occurrence {index}", "score": .9,
              "box": [[left, top], [right, top], [right, bottom], [left, bottom]]}
             for index, (left, top, right, bottom) in enumerate(bounds)]
    return {"text": "\n".join(line["text"] for line in lines), "lines": lines, "mean_confidence": .9,
            "raster": {"width": 1000, "height": 1000, "dpi": 300, "coordinate_system": "rendered_image_pixels"},
            "engine": {"name": "rapidocr", "version": "synthetic-no-execution", "min_score": 0., "max_side": 6000}}


def _document():
    document = {"schema_name": "DoclingDocument", "version": "1.0.0",
                "pages": {str(number): {"page_no": number, "size": {"width": 240, "height": 240}}
                           for number in (1, 2)}, "texts": [], "tables": [], "pictures": [], "groups": [],
                "body": {"self_ref": "#/body", "children": []},
                "furniture": {"self_ref": "#/furniture", "children": []}}
    for number in (1, 2):
        for tree, bounds in (("furniture", (50, 20, 950, 150)), ("body", (50, 250, 450, 600)),
                             ("body", (550, 250, 950, 600)), ("furniture", (50, 850, 950, 980))):
            ref = f"#/texts/{len(document['texts'])}"
            left, top, right, bottom = [value * .24 for value in bounds]
            document["texts"].append({"self_ref": ref, "label": "text", "text": "Synthetic region",
                "children": [], "prov": [{"page_no": number, "bbox": {
                    "l": left, "t": top, "r": right, "b": bottom, "coord_origin": "TOPLEFT"}}]})
            document[tree]["children"].append({"$ref": ref})
    return document


