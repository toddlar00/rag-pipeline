def test_gradio_suggestion_and_preview_have_explicit_private_click_only_paths(ui):
    app = ui.app
    dependencies = app.config["dependencies"]
    for dependency in dependencies:
        assert dependency["api_visibility"] == "private"
    named = {block.fn.__name__: (index, block) for index, block in app.fns.items() if block.fn is not None}
    suggest_index, suggest = named["suggest_columns"]
    preview_index, preview = named["preview"]
    assert suggest.concurrency_id == preview.concurrency_id == "ocr-review"
    assert suggest.concurrency_limit == preview.concurrency_limit == 1
    preview_dependency = next(item for item in dependencies if item["id"] == preview_index)
    assert preview_dependency["trigger_after"] is None
    assert all(event == "click" for _, event in preview_dependency["targets"])
    prose = next(component for component in preview.inputs if type(component).__name__ == "Checkbox")
    assert prose.value is False and "prose" in prose.label.lower() and "table" in prose.label.lower()
    assert "left-to-right" in prose.label.lower()
    ancestors = {suggest_index}
    for _ in range(len(dependencies)):
        ancestors.update(item["id"] for item in dependencies if item["trigger_after"] in ancestors)
    assert preview_index not in ancestors
    for dependency in dependencies:
        if any(component == prose._id for component, _ in dependency["targets"]):
            assert dependency["id"] != preview_index
    assert all(type(component).__name__ != "Checkbox" for component in suggest.inputs)


def _block(ui, name):
    return next(block for block in ui.app.fns.values() if block.fn is not None and block.fn.__name__ == name)


async def _capture_queued(ui, block, inputs, *, session_hash):
    """Use the installed transport queue's real retained request input body."""
    from fastapi import Request
    from gradio.data_classes import PredictBodyInternal

    request = Request({"type": "http", "method": "POST", "path": "/gradio_api/queue/join",
                       "root_path": "", "headers": [], "query_string": b"", "scheme": "http",
                       "server": ("127.0.0.1", 7860), "client": ("127.0.0.1", 1)})
    index = next(index for index, candidate in ui.app.fns.items() if candidate is block)
    body = PredictBodyInternal(data=copy.deepcopy(inputs), fn_index=index,
                               session_hash=session_hash, request=request)
    accepted, event_id, status = await ui.app._queue.push(body, request, None)
    assert accepted and status == "success"
    event = ui.app._queue.event_ids_to_events[event_id]
    assert event.data.data == inputs and event.concurrency_id == "ocr-review"
    return event


async def _process(ui, block, inputs, session, session_hash):
    return await ui.app.process_api(block, inputs=inputs, state=session, session_hash=session_hash)


@pytest.mark.parametrize("synchronize", [False, True])
def test_queued_previous_page_prose_confirmation_cannot_preview_new_suggestion(ui, synchronize):
    """A real queued old token + True cannot consume the newer live State."""
    async def scenario():
        session_hash = "generated-stale-column-preview"
        session = ui.app.state_holder[session_hash]
        preview = _block(ui, "preview")
        state_id = preview.inputs[0]._id
        first = _suggest(ui)[1]
        session[state_id] = first
        queued = await _capture_queued(ui, preview, [None, True, first["column_context"]], session_hash=session_hash)
        await _process(ui, _block(ui, "change_page"), [2, None, "", first["annotation_context"]], session, session_hash)
        response = await _process(ui, _block(ui, "suggest_columns"), [None], session, session_hash)
        assert response["data"][4:6] == [False, False]
        current = copy.deepcopy(session[state_id])
        assert current["page"] == 2 and current["column_context"] != first["column_context"]
        if synchronize:
            synced = await _process(ui, _block(ui, "sync_column_context"), [None], session, session_hash)
            assert synced["data"] == [current["column_context"], False, False, False, False]
        with pytest.raises(Exception, match="Review action failed"):
            await _process(ui, queued.fn, queued.data.data, session, session_hash)
        assert session[state_id] == current and current["layouts"] == []
        assert not list(ui.workspace.output_dir.glob("ocr-layout-*.json"))

    asyncio.run(scenario())


