def test_matching_synchronized_client_context_allows_explicit_preview_and_export(ui):
    async def scenario():
        session_hash = "generated-current-column-context"
        session = ui.app.state_holder[session_hash]
        preview = _block(ui, "preview")
        state_id = preview.inputs[0]._id
        session[state_id] = copy.deepcopy(ui.state)
        await _process(ui, _block(ui, "suggest_columns"), [None], session, session_hash)
        first = await _process(ui, _block(ui, "sync_column_context"), [None], session, session_hash)
        assert first["data"][1:] == [False] * 4
        queued = await _capture_queued(ui, preview, [None, True, first["data"][0]], session_hash=session_hash)
